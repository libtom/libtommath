static int s_mp_search_5_smooth_array(const int a[], int size, int target)
{
   int low = 0;
   int high = size;

   while (low < high) {
      int mid = low + (high - low) / 2;

      if (a[mid] <= target) {
         low = mid + 1;
      } else {
         high = mid;
      }
   }
   return low;
}

int s_mp_ntt_smooth_length_table(int need)
{
   int idx = 0, array_size = 0;

   if (need <= 1) {
      return 1;
   }

   if (need == (1<<31)) {
      return (1<<31);
   }

   array_size = (int)(sizeof(five_smooth) / sizeof(five_smooth[0]));

   idx = s_mp_search_5_smooth_array(five_smooth, array_size, need);
   if (idx == (int)array_size) {
      idx--;
   }
   return five_smooth[idx];
}

